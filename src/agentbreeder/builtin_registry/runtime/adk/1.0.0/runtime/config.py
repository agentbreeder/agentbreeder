"""Runtime configuration: the data-only agent.config.json, deploy-time services and secret files.

Nothing here is code from the agent author: `agent.config.json` is generated by
`agentbreeder build` from agent.yaml + agent.lock, and artifacts are hashed registry copies.

Secrets are read from files (`<NAME>_FILE`, mounted read-only by `agentbreeder deploy`). For local
development only, `AGENTBREEDER_DEV_PLAIN_SECRETS=1` also allows `<NAME>` from the environment;
the deploy engine never sets that.
"""

from __future__ import annotations

import json
import os
from functools import cache
from pathlib import Path

APP_DIR = Path(os.getenv("AGENTBREEDER_APP_DIR", Path(__file__).resolve().parent.parent))


class ConfigError(RuntimeError):
    pass


@cache
def config() -> dict:
    path = APP_DIR / "agent.config.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ConfigError(f"cannot read {path}") from error
    if not isinstance(data, dict) or not data.get("name") or not data.get("model"):
        raise ConfigError(f"{path} is missing name or model")
    return data


def artifact(relative: str) -> Path:
    """Resolve an artifact dir from the config, refusing anything outside APP_DIR."""
    path = (APP_DIR / relative).resolve()
    if APP_DIR.resolve() not in path.parents:
        raise ConfigError(f"artifact path escapes the app dir: {relative}")
    return path


def secret(name: str) -> str:
    file = os.getenv(f"{name}_FILE")
    if file:
        try:
            return Path(file).read_text(encoding="utf-8").strip()
        except OSError as error:
            raise ConfigError(f"cannot read secret file for {name}") from error
    if os.getenv("AGENTBREEDER_DEV_PLAIN_SECRETS") == "1" and os.getenv(name):
        return os.environ[name]  # DEV ONLY: plain env secrets (never set by agentbreeder deploy)
    raise ConfigError(f"{name}_FILE is not set (mount it with a secret:// reference)")


def service(name: str, default: str = "") -> str:
    return os.getenv(f"AGENTBREEDER_SERVICE_{name.upper()}", default).rstrip("/")


def gateway_url() -> str:
    return os.getenv("AGENTBREEDER_GATEWAY_URL", "http://host.docker.internal:4000").rstrip("/")


def sessions_database() -> str:
    """ADK sessions live in a sibling database on the same server (its tables differ)."""
    return os.getenv("AGENTBREEDER_SESSIONS_DATABASE", "adk")
