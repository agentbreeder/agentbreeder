"""A Helm 3 chart for a locked stack's services, rendered from the same plan as the Compose file
(#772 K3; spec docs/superpowers/specs/2026-11-14-production-kubernetes-design.md §5.1-§5.3).

Pure: no cluster, no `helm` binary, no secret value. The chart directory:

- `Chart.yaml`, `values.yaml` (per-tier enable flags only), `.helmignore`;
- `templates/<service>.yaml`: its ServiceAccount (automount off), ConfigMaps for its `files/`
  directory and file params, a Deployment (a StatefulSet with `volumeClaimTemplates` when it has
  volumes, plus a headless Service), and a ClusterIP Service. Each file is wrapped in
  `{{- if .Values.tiers.tierN }}`; every other `{{` is escaped as `{{"{{"}}`, so nothing else is
  a template action;
- `jobs/<service>-init.yaml`, `jobs/<service>-bootstrap.yaml`: the steps `services up` runs,
  never part of the release (no Helm hooks; spec §5.4 applies them in order);
- `agentbreeder.lock`: renderer, stack.lock digest, images, tiers and every Secret the chart
  references, by name only.

Secrets are references: a pod's `/run/secrets` is a projected volume of `ab-svc-*` Secrets
(one per resolved value, key `value`), which the installer creates (K4). `scan` refuses a chart
that contains any known secret value (CHART_SECRET_LEAK); `check` refuses an object outside the
hardened shapes (CHART_HARDENING, CHART_EXPOSURE_REFUSED). NetworkPolicies are K6.
"""

