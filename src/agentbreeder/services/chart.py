RENDERED = frozenset(
    {"Chart.yaml", "values.yaml", ".helmignore", "agentbreeder.lock", "templates", "jobs"}
)


def _previous_render(directory: Path) -> bool:
    """Only a directory holding nothing but what render writes is replaced: a file the
    operator added beside the chart (a README, a values override) makes it refused."""
    if any(entry.name not in RENDERED for entry in directory.iterdir()):
        return False
    try:
        record = json.loads((directory / "agentbreeder.lock").read_text())
    except (OSError, ValueError):
        return False
    return isinstance(record, dict) and record.get("chart_format") == CHART_FORMAT


def write(files: dict[str, bytes], out: Path) -> Path:
    """Write the chart to `out`: a new directory, or replace a previous render (holding nothing
    else) whole. Any other non-empty directory is refused, as are a symlink and a file."""
    if out.is_symlink() or (out.exists() and not out.is_dir()):
        raise ServiceError("CHART_OUT_INVALID", f"{out} must be a directory (not a link or file)")
    target = out.resolve()
    if target.exists() and any(target.iterdir()) and not _previous_render(target):
        raise ServiceError(
            "CHART_OUT_NOT_EMPTY",
            f"{out} is not empty and holds no previous render; choose a new directory",
        )
    target.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{target.name}.", dir=target.parent))
    try:
        for path, data in files.items():
            destination = staging / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(data)
            destination.chmod(0o644)
        staging.chmod(0o755)
        if target.exists():
            old = Path(tempfile.mkdtemp(prefix=f".{target.name}.old.", dir=target.parent))
            os.replace(target, old / target.name)
            os.replace(staging, target)
            shutil.rmtree(old)
        else:
            os.replace(staging, target)
    finally:
        if staging.exists():
            shutil.rmtree(staging)
    return target
