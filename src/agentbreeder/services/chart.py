CHART_FORMAT = 1
FILES_LIMIT = 900 * 1024  # per ConfigMap; the API's limit is 1 MiB (spec §5.2)
SCAN_MIN = 8  # shorter known values are not scanned: they match ordinary text
KUBE_VERSION = ">=1.30.0-0"  # D14: ValidatingAdmissionPolicy GA
PART_OF = "agentbreeder-services"
CHART_SERVICE = "io.agentbreeder/chart-service"
STORAGE = "10Gi"  # per volumeClaimTemplate (to measure; no service.yaml field yet)
TMP_SIZE = "64Mi"  # as Compose's /tmp tmpfs
EXTRA_TMP_SIZE = "16Mi"
SECRET_MODE = 0o444
JOB_DEADLINE = 300  # seconds, as `oneshot`
# Used where service.yaml sets no `resources` (to measure per image).
DEFAULT_RESOURCES = {
    "requests": {"cpu": "100m", "memory": "256Mi"},
    "limits": {"cpu": "2", "memory": "2Gi"},
}
HEADER = "# Generated by `agentbreeder services render --cluster`; do not edit.\n"
ESCAPE = '{{"{{"}}'
_DNS = re.compile(r"[^a-z0-9]+")
_PORT_NAME = re.compile(r"[a-z0-9]([a-z0-9-]{0,13}[a-z0-9])?")
_CONFIG_KEY = re.compile(r"[-._a-zA-Z0-9]{1,253}")
_DIGEST = re.compile(r"@sha256:[a-f0-9]{64}$")
# A pushed image: service.yaml's IMAGE form, optionally behind a registry host with a port
# (`localhost:5001/x@sha256:...`). No userinfo.
IMAGE_REF = re.compile(
    r"([a-z0-9][a-z0-9.-]{0,252}(:[0-9]{1,5})?/)?[a-z0-9][a-z0-9./_-]{0,254}"
    r"(:[A-Za-z0-9._-]{1,128})?@sha256:[a-f0-9]{64}"
)
# The only kinds a chart or its jobs may hold.
KINDS = {"ServiceAccount", "ConfigMap", "Service", "Deployment", "StatefulSet", "Job"}
EXPOSURE_KINDS = {"Ingress", "IngressClass", "Gateway", "HTTPRoute", "Route"}
VOLUME_TYPES = {"emptyDir", "configMap", "projected"}


def renderer() -> str:
    from agentbreeder import __version__

    return __version__


# -- names -----------------------------------------------------------------------------------


def _dns(text: str) -> str:
    return _DNS.sub("-", text.lower()).strip("-")


def secret_name(key: str, generation: int = 1) -> str:
    """`ab-svc-<readable>-<hash>-g<generation>` (DNS-1123, at most 63 characters) for one
    resolved value: `key` is `<service>/secret/<name>[.<item>]` or
    `<service>/output/<name>[.<item>]`. The hash of the exact key keeps names unique where the
    readable part folds `_`, `.` and `-` together; a long readable part is cut."""
    service, _, path = key.partition("/")
    path = path.partition("/")[2]
    suffix = f"-{hashlib.sha256(key.encode()).hexdigest()[:6]}-g{generation}"
    room = 63 - len("ab-svc-") - len(suffix)
    readable = _dns(f"{service}-{path}")[:room].rstrip("-")
    return f"ab-svc-{readable}{suffix}"


def _account(service: str) -> str:
    return f"ab-svc-{service}"


def _labels(stack: str, service: str) -> dict[str, str]:
    return {
        "app.kubernetes.io/part-of": PART_OF,
        "app.kubernetes.io/managed-by": "agentbreeder",
        "io.agentbreeder/stack": stack,
        "io.agentbreeder/service": service,
    }


def _escape_dollars(value: str) -> str:
    """Kubernetes expands `$(VAR)` in env values, command and args, and reduces `$$` to `$`:
    doubling every `$` keeps each string literal."""
    return value.replace("$", "$$")


# -- resources and security --------------------------------------------------------------------


def resources(spec: ServiceSpec) -> dict:
    result = json.loads(json.dumps(DEFAULT_RESOURCES))
    given = spec.resources
    if given is not None:
        for part in ("requests", "limits"):
            for key, value in getattr(given, part).model_dump(exclude_none=True).items():
                result[part][key] = value
    return result


def pod_security(service: str, spec: ServiceSpec) -> dict:
    """The pod's securityContext: `restricted` Pod Security. A fixed `uid:gid` runs as that
    user (and owns its volumes through fsGroup); `image` keeps the image's user, which the
    kubelet refuses if it is root or not numeric."""
    context: dict = {"runAsNonRoot": True, "seccompProfile": {"type": "RuntimeDefault"}}
    if spec.user == "host":
        raise ServiceError(
            "CHART_USER_HOST",
            f"service {service} runs as the operator's uid (user: host), which a cluster has not",
        )
    if spec.user != "image":
        uid, gid = (int(part) for part in spec.user.split(":"))
        if uid == 0:
            raise ServiceError(
                "CHART_ROOT_USER", f"service {service} runs as root, which `restricted` refuses"
            )
        context.update({"runAsUser": uid, "runAsGroup": gid})
        if spec.volumes:
            context["fsGroup"] = gid
    return context


CONTAINER_SECURITY = {
    "allowPrivilegeEscalation": False,
    "capabilities": {"drop": ["ALL"]},
    "readOnlyRootFilesystem": True,
    "runAsNonRoot": True,
    "seccompProfile": {"type": "RuntimeDefault"},
}


# -- the chart ---------------------------------------------------------------------------------


@dataclass
class Mounted:
    """One file at /run/secrets: the Secret holding its value and whether it may be absent."""

    path: str
    secret: str
    optional: bool


@dataclass
class Chart:
    name: str
    version: str
    stack: str
    environment: str
    tiers: list[list[str]]
    documents: list[dict] = field(default_factory=list)  # every release object
    templates: dict[str, tuple[int, list[dict]]] = field(default_factory=dict)  # svc -> tier
    jobs: dict[str, dict] = field(default_factory=dict)  # file stem -> Job
    record: dict = field(default_factory=dict)  # agentbreeder.lock

    def files(self) -> dict[str, bytes]:
        meta = {
            "apiVersion": "v2",
            "name": self.name,
            "description": f"AgentBreeder services for stack {self.stack} "
            f"(environment {self.environment}); generated, not published",
            "type": "application",
            "version": self.version,
            "appVersion": self.version.partition("+")[2],
            "kubeVersion": KUBE_VERSION,
            "annotations": {
                "io.agentbreeder/chart-format": str(CHART_FORMAT),
                "io.agentbreeder/environment": self.environment,
                "io.agentbreeder/stack-lock-sha256": self.record["stack_lock_sha256"],
            },
        }
        values = HEADER
        values += "# Non-secret knobs only. Tiers install in order (services up --cluster).\n"
        values += "tiers:\n" + "".join(
            f"  tier{index}: true  # {', '.join(names)}\n"
            for index, names in enumerate(self.tiers)
        )
        result = {
            "Chart.yaml": (HEADER + _dump(meta)).encode(),
            "values.yaml": values.encode(),
            ".helmignore": b"jobs/\nagentbreeder.lock\n",
            "agentbreeder.lock": (json.dumps(self.record, indent=2) + "\n").encode(),
        }
        for service, (tier, documents) in sorted(self.templates.items()):
            body = _dump_all(documents).replace("{{", ESCAPE)
            text = (
                f"{HEADER}# Service {service}, tier {tier}.\n"
                f"{{{{- if .Values.tiers.tier{tier} }}}}\n{body}{{{{- end }}}}\n"
            )
            result[f"templates/{service}.yaml"] = text.encode()
        for stem, job in sorted(self.jobs.items()):
            note = "# Applied by the installer after its service is ready; not in the release.\n"
            result[f"jobs/{stem}.yaml"] = (HEADER + note + _dump(job)).encode()
        return result


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data) -> bool:  # every object written out in full, no anchors
        return True


# Plain scalars Helm's YAML 1.1 loader may read as a number, bool or null although PyYAML leaves
# them unquoted (`1e3`, `y`, `0o17`, an appVersion such as `123456789e12`): always quoted.
_AMBIGUOUS = re.compile(
    r"[-+]?\.?[0-9].*|[-+]?\.(inf|Inf|INF|nan|NaN|NAN)|(?i:y|n|yes|no|on|off|true|false|null|~)|"
)


def _string(dumper, value: str):
    if "\n" in value:
        style = "|"
    elif _AMBIGUOUS.fullmatch(value):
        style = "'"
    else:
        style = None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _string)


def _dump(document) -> str:
    return yaml.dump(document, Dumper=_Dumper, sort_keys=False, width=4096)


def _dump_all(documents) -> str:
    return yaml.dump_all(
        documents, Dumper=_Dumper, explicit_start=True, sort_keys=False, width=4096
    )


def tiers(plan: Plan) -> dict[str, int]:
    """A service's tier: 0 without wired upstreams, else one more than its highest upstream.
    `services up --cluster` installs tier by tier, the order `engine._start` uses."""
    result: dict[str, int] = {}
    stack = plan.locked.stack
    for name in plan.locked.resolved.order:
        upstream = [Reference.parse(t, "wire").service for t in stack.services[name].wire.values()]
        result[name] = 1 + max((result[u] for u in upstream), default=-1)
    return result


class _Builder:
    def __init__(self, plan: Plan, environment: str, images: dict[str, str]):
        self.plan = plan
        self.environment = environment
        self.images = images
        self.stack = plan.locked.stack.name
        self.secrets: dict[str, dict] = {}  # Secret name -> what it holds (agentbreeder.lock)

    # -- secrets ---------------------------------------------------------------------------

    def _own(self, service: str, name: str, item: str | None) -> str:
        """The Secret of one of `service`'s own secrets (per-item as `name.item`)."""
        spec = self.plan.spec(service)
        source = spec.secrets.get(name)
        path = f"{name}.{item}" if source is not None and source.per and item else name
        key = f"{service}/secret/{path}"
        secret = secret_name(key)
        if source is None:
            origin = "bootstrap"
        elif source.import_:
            origin = f"import {source.import_}"
        else:
            origin = "generate"
        whole = [o for o in spec.outputs.values() if o.secret == name and o.template is None]
        flags = {f for o in whole for f in ("operator_only", "services_only") if getattr(o, f)}
        self._record(secret, service, f"secret {path}", origin, flags)
        return secret

    def _record(self, secret, service, value, origin, flags) -> None:
        entry = {"service": service, "value": value, "source": origin}
        entry.update({flag: True for flag in sorted(flags)})
        known = self.secrets.setdefault(secret, entry)
        if known != entry:  # pragma: no cover - the hash makes this a broken invariant
            raise ServiceError("CHART_SECRET_NAME", f"two values share the Secret name {secret}")

    def _output(self, reference: Reference) -> tuple[str, bool]:
        """The Secret holding a wired secret output's resolved value, and whether it may be
        absent until a bootstrap writes it."""
        producer = self.plan.spec(reference.service)
        output = producer.outputs[reference.output]
        written = set(producer.bootstrap.written()) if producer.bootstrap else set()
        if output.secret is not None:
            secret = self._own(reference.service, output.secret, reference.item)
            return secret, output.secret in written
        path = reference.output + (f".{reference.item}" if reference.item else "")
        key = f"{reference.service}/output/{path}"
        secret = secret_name(key)
        flags = {f for f in ("operator_only", "services_only") if getattr(output, f)}
        self._record(secret, reference.service, f"output {path}", "output", flags)
        uses = {f"secret.{name}" for name in written}
        return secret, any(u in (output.template or "") for u in uses)

    def mounted(self, service: str, wanted: set[str] | None = None) -> list[Mounted]:
        """What `Plan.mounted` would bind at /run/secrets, as Secret references."""
        spec = self.plan.spec(service)
        wanted = spec.mounted_secrets() if wanted is None else wanted
        params = self.plan.locked.resolved.params[service]
        result: list[Mounted] = []
        for name, source in sorted(spec.secrets.items()):
            if name not in wanted:
                continue
            items = params.get(source.per) or [] if source.per else [None]
            for item in items:
                # As `StackState.mount_dir`: per-item values are files in a directory.
                path = f"{name}/{item}" if item else name
                result.append(Mounted(path, self._own(service, name, item), source.optional))
        if spec.bootstrap is not None:
            for name in spec.bootstrap.written():
                if name in wanted:
                    result.append(Mounted(name, self._own(service, name, None), True))
        wires = self.plan.locked.stack.services[service].wire
        for name, spec_input in sorted(spec.inputs.items()):
            if spec_input.type == "secret" and name in wanted and name in wires:
                secret, optional = self._output(Reference.parse(wires[name], name))
                result.append(Mounted(name, secret, optional))
        return sorted(result, key=lambda m: m.path)

    # -- config maps -----------------------------------------------------------------------

    def _config_map(self, service: str, suffix: str, entries: dict[str, Path]) -> dict:
        data: dict[str, str] = {}
        binary: dict[str, str] = {}
        total = 0
        for key, path in sorted(entries.items()):
            if not _CONFIG_KEY.fullmatch(key):
                raise ServiceError(
                    "CHART_FILES_INVALID", f"service {service}: {key!r} can't be a ConfigMap key"
                )
            content = path.read_bytes()
            try:
                data[key] = content.decode("utf-8")
                total += len(content)
            except UnicodeDecodeError:
                binary[key] = base64.b64encode(content).decode()
                total += len(binary[key])  # stored base64-encoded
        if total > FILES_LIMIT:
            raise ServiceError(
                "CHART_FILES_TOO_LARGE",
                f"service {service}: its {suffix} are {total} bytes; a ConfigMap holds at most "
                f"{FILES_LIMIT} here",
            )
        document = {
            "apiVersion": "v1",
            "kind": "ConfigMap",
            "metadata": {
                "name": f"ab-svc-{service}-{suffix}",
                "labels": _labels(self.stack, service),
            },
        }
        if data:
            document["data"] = data
        if binary:
            document["binaryData"] = binary
        return document

    def _files(self, service: str) -> dict[str, Path]:
        directory = self.plan.service_files.get(service)
        if directory is None:
            return {}
        entries = {}
        for path in sorted(directory.iterdir()):
            if not path.is_file() or path.is_symlink():
                raise ServiceError(
                    "CHART_FILES_INVALID",
                    f"service {service}: files/ may hold only regular files on a cluster "
                    f"({path.name} is not one)",
                )
            entries[path.name] = path
        return entries

    # -- pods ------------------------------------------------------------------------------

    def _volumes(self, service: str, mounted: list[Mounted], files: dict[str, Path]):
        spec = self.plan.spec(service)
        volumes = [{"name": "tmp", "emptyDir": {"medium": "Memory", "sizeLimit": TMP_SIZE}}]
        mounts = [{"name": "tmp", "mountPath": "/tmp"}]
        for index, path in enumerate(spec.tmpfs):
            name = f"scratch-{index}"
            scratch = {"medium": "Memory", "sizeLimit": EXTRA_TMP_SIZE}
            volumes.append({"name": name, "emptyDir": scratch})
            mounts.append({"name": name, "mountPath": path})
        if files:
            items = [
                {"key": key, "path": key, "mode": 0o555 if os.access(path, os.X_OK) else 0o444}
                for key, path in sorted(files.items())
            ]
            volumes.append(
                {
                    "name": "files",
                    "configMap": {"name": f"ab-svc-{service}-files", "items": items},
                }
            )
            mounts.append({"name": "files", "mountPath": "/files", "readOnly": True})
        if self.plan.files.get(service):
            volumes.append(
                {
                    "name": "params",
                    "configMap": {
                        "name": f"ab-svc-{service}-params",
                        "defaultMode": SECRET_MODE,
                    },
                }
            )
            mounts.append({"name": "params", "mountPath": "/run/params", "readOnly": True})
        if mounted:
            sources = [
                {
                    "secret": {
                        "name": m.secret,
                        "items": [{"key": "value", "path": m.path}],
                        "optional": m.optional,
                    }
                }
                for m in mounted
            ]
            volumes.append(
                {"name": "secrets", "projected": {"defaultMode": SECRET_MODE, "sources": sources}}
            )
            mounts.append({"name": "secrets", "mountPath": "/run/secrets", "readOnly": True})
        return volumes, mounts

    def _container(self, service: str, command: list[str] | None, mounts: list[dict]) -> dict:
        spec = self.plan.spec(service)
        container: dict = {"name": service, "image": self.images[service]}
        if command:
            container["command"] = [_escape_dollars(command[0])]
            if command[1:]:
                container["args"] = [_escape_dollars(part) for part in command[1:]]
        environment = self.plan.environment(service)
        container["env"] = [
            {"name": key, "value": _escape_dollars(value)}
            for key, value in sorted(environment.items())
        ]
        container["resources"] = resources(spec)
        container["securityContext"] = json.loads(json.dumps(CONTAINER_SECURITY))
        container["volumeMounts"] = mounts
        return container

    def _pod(self, service: str, container: dict, volumes: list[dict], job: bool) -> dict:
        spec = self.plan.spec(service)
        pod = {
            "serviceAccountName": _account(service),
            "automountServiceAccountToken": False,
            "enableServiceLinks": False,
            "securityContext": pod_security(service, spec),
            "containers": [container],
            "volumes": volumes,
        }
        if job:
            pod = {"restartPolicy": "Never", **pod}
        return pod

    def _probe(self, service: str) -> dict | None:
        health = self.plan.spec(service).health
        if health is None:
            return None
        timing = {"periodSeconds": 3, "timeoutSeconds": 5, "failureThreshold": 3}
        if health.command:
            return {"exec": {"command": list(health.command)}, **timing}
        port_name = health.port or next(iter(self.plan.spec(service).ports))
        port = self.plan.spec(service).ports[port_name].port
        # The Host header the local probe sends (`http://<service>:<port>`): a host-allowlist
        # guard accepts it.
        return {
            "httpGet": {
                "path": health.http,
                "port": port,
                "httpHeaders": [{"name": "Host", "value": f"{service}:{port}"}],
            },
            **timing,
        }

    def _ports(self, service: str) -> list[tuple[str, int]]:
        result = []
        for name, port in sorted(self.plan.spec(service).ports.items()):
            readable = _dns(name)
            if not _PORT_NAME.fullmatch(readable) or not re.search("[a-z]", readable):
                readable = f"p{port.port}"
            result.append((readable, port.port))
        if len({name for name, _ in result}) != len(result):
            raise ServiceError("CHART_PORT_NAME", f"service {service}: port names collide")
        return result

    # -- per service -----------------------------------------------------------------------

    def service(self, service: str) -> tuple[list[dict], dict[str, dict]]:
        spec = self.plan.spec(service)
        labels = _labels(self.stack, service)
        documents: list[dict] = [
            {
                "apiVersion": "v1",
                "kind": "ServiceAccount",
                "metadata": {"name": _account(service), "labels": labels},
                "automountServiceAccountToken": False,
            }
        ]
        files = self._files(service)
        if files:
            documents.append(self._config_map(service, "files", files))
        params = self.plan.files.get(service) or {}
        if params:
            documents.append(self._config_map(service, "params", dict(params)))
        mounted = self.mounted(service)
        volumes, mounts = self._volumes(service, mounted, files)
        for name, target in sorted(spec.volumes.items()):
            mounts.append({"name": f"data-{_dns(name)}", "mountPath": target})
        container = self._container(service, spec.command, mounts)
        ports = self._ports(service)
        if ports:
            container["ports"] = [
                {"name": name, "containerPort": number, "protocol": "TCP"}
                for name, number in ports
            ]
        probe = self._probe(service)
        if probe is not None:
            container["readinessProbe"] = probe
        pod = self._pod(service, container, volumes, job=False)
        config = hashlib.sha256(
            json.dumps([documents[1:], pod], sort_keys=True).encode()
        ).hexdigest()
        template = {
            "metadata": {
                "labels": {**labels, CHART_SERVICE: service},
                "annotations": {"io.agentbreeder/config-sha256": config},
            },
            "spec": pod,
        }
        workload: dict = {
            "apiVersion": "apps/v1",
            "kind": "StatefulSet" if spec.volumes else "Deployment",
            "metadata": {"name": service, "labels": labels},
            "spec": {
                "replicas": 1,
                "revisionHistoryLimit": 2,
                "selector": {"matchLabels": {CHART_SERVICE: service}},
            },
        }
        if spec.volumes:
            names = [f"data-{_dns(name)}" for name in sorted(spec.volumes)]
            if len(set(names)) != len(names):
                raise ServiceError("CHART_VOLUME_NAME", f"service {service}: volume names collide")
            workload["spec"]["serviceName"] = f"{service}-headless"
            workload["spec"]["template"] = template
            workload["spec"]["volumeClaimTemplates"] = [
                {
                    "metadata": {"name": name, "labels": labels},
                    "spec": {
                        "accessModes": ["ReadWriteOnce"],
                        "resources": {"requests": {"storage": STORAGE}},
                    },
                }
                for name in names
            ]
        else:
            workload["spec"]["template"] = template
        documents.append(workload)
        if ports:
            service_ports = [
                {"name": name, "port": number, "targetPort": number, "protocol": "TCP"}
                for name, number in ports
            ]
            if spec.volumes:
                documents.append(
                    self._service(f"{service}-headless", service, service_ports, headless=True)
                )
            documents.append(self._service(service, service, service_ports, headless=False))
        jobs = {}
        for label, step in (("init", spec.init), ("bootstrap", spec.bootstrap)):
            if step is not None:
                jobs[f"{service}-{label}"] = self._job(service, label, step, files)
        return documents, jobs

    def _service(self, name: str, service: str, ports: list[dict], headless: bool) -> dict:
        body: dict = {"type": "ClusterIP"}
        if headless:
            body["clusterIP"] = "None"
        body.update({"selector": {CHART_SERVICE: service}, "ports": ports})
        return {
            "apiVersion": "v1",
            "kind": "Service",
            "metadata": {"name": name, "labels": _labels(self.stack, service)},
            "spec": body,
        }

    def _job(self, service: str, label: str, step, files: dict[str, Path]) -> dict:
        mounted = self.mounted(service, set(step.secrets))
        volumes, mounts = self._volumes(service, mounted, files)
        container = self._container(service, list(step.command), mounts)
        labels = {**_labels(self.stack, service), "io.agentbreeder/step": label}
        return {
            "apiVersion": "batch/v1",
            "kind": "Job",
            "metadata": {"name": f"ab-svc-{service}-{label}", "labels": labels},
            "spec": {
                "backoffLimit": 0,
                "activeDeadlineSeconds": JOB_DEADLINE,
                "ttlSecondsAfterFinished": 600,
                "template": {
                    "metadata": {"labels": labels},
                    "spec": self._pod(service, container, volumes, job=True),
                },
            },
        }


def _images(plan: Plan, given: dict[str, str]) -> dict[str, str]:
    """Every service's image by digest: service.yaml's own, or `given` for a built service
    (pushed by the operator; K4 mirrors and pushes). Nothing else may be overridden."""
    result = {}
    for name, image in sorted(given.items()):
        spec = plan.locked.specs.get(name)
        if spec is None or spec.image is not None:
            raise ServiceError(
                "CHART_IMAGE_INVALID",
                f"--image {name}: only a service built from a Dockerfile takes an image",
            )
        if not IMAGE_REF.fullmatch(image):
            raise ServiceError(
                "CHART_IMAGE_INVALID", f"--image {name}: give an image reference by @sha256 digest"
            )
    for name in plan.locked.resolved.order:
        spec = plan.spec(name)
        if spec.image is not None:
            result[name] = spec.image
        elif name in given:
            result[name] = given[name]
        else:
            raise ServiceError(
                "CHART_IMAGE_REQUIRED",
                f"service {name} is built from a Dockerfile: push it and pass "
                f"--image {name}=REGISTRY/NAME@sha256:DIGEST",
            )
    return result


def build(
    plan: Plan,
    environment: str,
    *,
    stack_lock_sha256: str,
    images: dict[str, str] | None = None,
) -> Chart:
    """The chart for `plan` in `environment`. Refuses what a cluster can't run as planned."""
    if plan.locked.mcp:
        raise ServiceError(
            "CHART_MCP_UNSUPPORTED",
            "stacks with mcp: entries can't be rendered for a cluster yet (relays need a "
            "separate design, #770 D6)",
        )
    gateway = plan.locked.stack.environment.gateway
    if plan._maps_host(gateway):
        raise ServiceError(
            "CHART_HOST_UNSUPPORTED",
            f"the {gateway} config routes a model to the operator's host "
            "(host.docker.internal), which a cluster can't reach",
        )
    resolved_images = _images(plan, images or {})
    builder = _Builder(plan, environment, resolved_images)
    tier_of = tiers(plan)
    order = sorted(plan.locked.resolved.order, key=lambda name: (tier_of[name], name))
    grouped: list[list[str]] = []
    for name in order:
        while len(grouped) <= tier_of[name]:
            grouped.append([])
        grouped[tier_of[name]].append(name)
    stack = plan.locked.stack.name
    chart = Chart(
        name=f"ab-{stack}",
        version=f"0.0.0+{stack_lock_sha256[:12]}",
        stack=stack,
        environment=environment,
        tiers=grouped,
    )
    steps: dict[str, list[str]] = {}
    for name in order:
        documents, jobs = builder.service(name)
        chart.templates[name] = (tier_of[name], documents)
        chart.documents += documents
        chart.jobs.update(jobs)
        if jobs:
            steps[name] = [stem.removeprefix(f"{name}-") for stem in jobs]
    check([*chart.documents, *chart.jobs.values()])
    chart.record = {
        "chart_format": CHART_FORMAT,
        "renderer": f"agentbreeder {renderer()}",
        "stack": stack,
        "environment": environment,
        "chart": chart.name,
        "version": chart.version,
        "stack_lock_sha256": stack_lock_sha256,
        "images": resolved_images,
        "tiers": grouped,
        "jobs": steps,
        "secrets": dict(sorted(builder.secrets.items())),
        "operator_only_secrets": sorted(
            name for name, entry in builder.secrets.items() if entry.get("operator_only")
        ),
    }
    return chart


# -- checks ------------------------------------------------------------------------------------


def _hardening(where: str, problem: str) -> ServiceError:
    return ServiceError("CHART_HARDENING", f"{where}: {problem}")


def _check_pod(where: str, pod: dict) -> None:
    for key in ("hostNetwork", "hostPID", "hostIPC", "initContainers", "ephemeralContainers"):
        if pod.get(key):
            raise _hardening(where, f"{key} is not allowed")
    if pod.get("automountServiceAccountToken") is not False:
        raise _hardening(where, "the service account token must not be mounted")
    if pod.get("enableServiceLinks") is not False:
        raise _hardening(where, "service links must be off")
    context = pod.get("securityContext") or {}
    if context.get("runAsNonRoot") is not True or context.get("runAsUser", 1) == 0:
        raise _hardening(where, "the pod must run as non-root")
    if context.get("seccompProfile") != {"type": "RuntimeDefault"}:
        raise _hardening(where, "the pod needs the RuntimeDefault seccomp profile")
    for volume in pod.get("volumes") or []:
        if set(volume) - {"name"} - VOLUME_TYPES:
            raise _hardening(where, f"volume {volume.get('name')} has a type outside the template")
    containers = pod.get("containers") or []
    if len(containers) != 1:
        raise _hardening(where, "a pod runs exactly one container")
    for container in containers:
        security = container.get("securityContext") or {}
        for key, value in CONTAINER_SECURITY.items():
            if security.get(key) != value:
                raise _hardening(where, f"container securityContext.{key} must be {value}")
        if set(security) - set(CONTAINER_SECURITY) - {"runAsUser", "runAsGroup"}:
            raise _hardening(where, "container securityContext has extra fields")
        if not _DIGEST.search(str(container.get("image", ""))):
            raise _hardening(where, "images are referenced by digest only")
        limits = (container.get("resources") or {}).get("limits") or {}
        if not {"cpu", "memory"} <= set(limits):
            raise _hardening(where, "cpu and memory limits are required")
        if any("hostPort" in port or "hostIP" in port for port in container.get("ports") or []):
            raise _hardening(where, "host ports are not allowed")


def check(documents: Iterable[dict]) -> None:
    """Refuse any object outside the shapes the renderer writes (defence in depth for §5.2's
    hardening and exposure rules)."""
    for document in documents:
        kind = document.get("kind")
        where = f"{kind} {(document.get('metadata') or {}).get('name', '')}".strip()
        if kind in EXPOSURE_KINDS:
            raise ServiceError("CHART_EXPOSURE_REFUSED", f"{where}: no public endpoint")
        if kind not in KINDS:
            raise _hardening(where, "this kind is not part of a services chart")
        spec = document.get("spec") or {}
        if kind == "Service":
            if spec.get("type", "ClusterIP") != "ClusterIP" or spec.get("externalIPs"):
                raise ServiceError(
                    "CHART_EXPOSURE_REFUSED", f"{where}: services are ClusterIP only"
                )
            if any("nodePort" in port for port in spec.get("ports") or []):
                raise ServiceError("CHART_EXPOSURE_REFUSED", f"{where}: no node ports")
        elif kind == "ServiceAccount":
            if document.get("automountServiceAccountToken") is not False:
                raise _hardening(where, "the service account token must not be mounted")
        elif kind in ("Deployment", "StatefulSet", "Job"):
            _check_pod(where, (spec.get("template") or {}).get("spec") or {})


def _leaves(value):
    """Every string inside an object (scanned before YAML encodes it)."""
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for item in value.values():
            yield from _leaves(item)
    elif isinstance(value, list):
        for item in value:
            yield from _leaves(item)


def chart_texts(chart: Chart) -> dict[str, bytes]:
    """The chart's files, plus each file with the renderer's encodings undone (the `{{`
    escape, `$$`, YAML's `''`) and every string of its objects per file, so a value is found
    whatever quoting or escaping the file gives it."""
    files = chart.files()
    texts = dict(files)
    for path, data in files.items():
        text = data.decode("utf-8", "replace")
        decoded = text.replace(ESCAPE, "{{").replace("$$", "$").replace("''", "'")
        texts[f"{path} (decoded)"] = decoded.encode()
    objects: dict[str, object] = {
        f"templates/{name}.yaml": documents for name, (_, documents) in chart.templates.items()
    }
    objects.update({f"jobs/{stem}.yaml": job for stem, job in chart.jobs.items()})
    objects["agentbreeder.lock"] = chart.record
    for path, value in objects.items():
        strings = list(_leaves(value))
        strings += [text.replace("$$", "$") for text in strings]
        texts[f"{path} (values)"] = "\n".join(strings).encode()
    return texts


def scan(files: dict[str, bytes], values: Iterable[bytes | str]) -> None:
    """Refuse the chart if any known secret value appears in any file, literally or in the
    forms the redactor knows (base64, URL- and JSON-escaped). Names the file, never the value.
    Only finds known values (spec T5)."""
    from agentbreeder import redaction

    usable = []
    for value in values:
        text = value.decode("utf-8", "replace") if isinstance(value, bytes) else str(value)
        if len(text.strip()) >= SCAN_MIN:
            usable.append(text)
    patterns = redaction.patterns(usable)
    if not patterns:
        return
    for path, data in sorted(files.items()):
        text = data.decode("utf-8", "replace")
        if any(pattern in text for pattern in patterns):
            raise ServiceError(
                "CHART_SECRET_LEAK",
                f"{path.partition(' (')[0]} contains a known secret value (one this stack "
                "stores, an imported variable's or one in --env-file); remove it from the "
                "stack's files and params, "
                "or leave a non-secret value out of --env-file (secrets reach pods only as "
                "Secret references)",
            )


