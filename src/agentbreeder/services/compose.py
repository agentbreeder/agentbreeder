"""The only place stacks touch Docker and Compose.

- Compose always runs with `-p agentbreeder-<stack-id>`, an explicit `-f` and
  `--project-directory` (the stack state dir), an empty `--env-file` and a sanitised
  environment: no COMPOSE_* or DOCKER_HOST variables, no `.env` auto-load.
- The generated file holds paths and non-secret values only; secrets are bind-mounted files.
- Errors never carry values: output is redacted (known secrets and the stack's env values) and
  only a short tail is shown.
- One-shot steps (`init`, `bootstrap`) run with `--rm --log-driver none`; stdout is read over
  attach with an 8 KiB cap, stderr is discarded.
"""

from __future__ import annotations

import json
import os
import re
import secrets
import subprocess
import threading
import time
from collections.abc import Callable, Iterable
from pathlib import Path

import yaml

from agentbreeder.egress.boundary import SIDECAR_BASE
from agentbreeder.services.plan import LABEL_STACK, TMPFS
from agentbreeder.services.schema import ServiceError
from agentbreeder.services.state import StackState, write_private

ONESHOT_LIMIT = 8 * 1024
PROBE_IMAGE = SIDECAR_BASE  # pinned python:3.12-slim, already used by the egress sidecar
PROBE = "import sys, urllib.request\nurllib.request.urlopen(sys.argv[1], timeout=3)\n"
_KEEP_ENV = ("PATH", "HOME", "USER", "TMPDIR", "DOCKER_CONFIG", "LANG", "LC_ALL")


def sanitised_environment() -> dict[str, str]:
    return {key: os.environ[key] for key in _KEEP_ENV if key in os.environ}


def redact(text: str, values: Iterable[bytes | str]) -> str:
    """The shared redactor (literal, base64, URL, JSON forms and URL passwords; S-09)."""
    from agentbreeder import redaction

    return redaction.redact(text, values)


class DockerCLI:
    """Runs docker on the authorised local context. `run` is injectable for tests."""

    def __init__(
        self,
        run: Callable = subprocess.run,
        popen: Callable = subprocess.Popen,
        clock: Callable = time.monotonic,
    ):
        self.context = ""
        self._run = run
        self._popen = popen
        self._clock = clock
        self.redactions: list[bytes | str] = []

    def authorize(self) -> None:
        from agentbreeder.runtime import Docker
        from agentbreeder.store import DeploymentError

        docker = Docker()
        try:
            docker.authorize()
        except DeploymentError as error:
            raise ServiceError("DOCKER_UNAVAILABLE", str(error)) from None
        self.context = docker.context

    def _argv(self, arguments) -> list[str]:
        return ["docker", *(["--context", self.context] if self.context else []), *arguments]

    def run(
        self,
        *arguments: str,
        timeout: int = 120,
        what: str | None = None,
        stdin: bytes = b"",
        binds: bool = False,
    ) -> str:
        """`binds`: the call publishes host ports (compose up|start|restart), so a taken port in
        its stderr is PORT_BUSY. Never set for exec or one-shot runs, whose stderr is the
        container's own output."""
        try:
            result = self._run(
                self._argv(arguments),
                capture_output=True,
                timeout=timeout,
                check=False,
                env=sanitised_environment(),
                **({"input": stdin} if stdin else {}),
            )
        except (OSError, subprocess.TimeoutExpired):
            raise ServiceError(
                "DOCKER_FAILED", f"{what or 'docker ' + arguments[0]} failed or timed out"
            ) from None
        stdout = _text(result.stdout)
        if result.returncode:
            from agentbreeder.runtime import busy_port, port_busy_message

            port = busy_port(_text(result.stderr)) if binds else None
            if port is not None:
                raise ServiceError(
                    "PORT_BUSY", port_busy_message(port, what or f"docker {arguments[0]}")
                )
            tail = redact(_text(result.stderr) or stdout, self.redactions).strip().splitlines()
            detail = "; ".join(line[:300] for line in tail[-5:])
            raise ServiceError(
                "DOCKER_FAILED",
                f"{what or 'docker ' + arguments[0]} failed" + (f": {detail}" if detail else ""),
            )
        return stdout.strip()

    # -- compose ------------------------------------------------------------------------------

    def write_compose(self, state: StackState, document: dict) -> None:
        text = "# Generated by `agentbreeder services up`. Paths and non-secret values only.\n"
        text += yaml.safe_dump(document, sort_keys=True)
        write_private(state.compose_path, text.encode())
        empty = state.directory / "compose.env"
        if not empty.exists():
            write_private(empty, b"")

    def compose(
        self, state: StackState, *arguments: str, timeout: int = 300, what=None, binds=False
    ) -> str:
        return self.run(
            "compose",
            "-p",
            state.project,
            "-f",
            str(state.compose_path),
            "--project-directory",
            str(state.directory),
            "--env-file",
            str(state.directory / "compose.env"),
            *arguments,
            timeout=timeout,
            what=what or f"docker compose {arguments[0]}",
            binds=binds,
        )

    def relay_probe(self, state: StackState, service: str, admin_token: bytes) -> str:
        """Run the MCP relay's probe inside its container (spec §7.7.1). The admin token goes
        on stdin: never in argv, the environment or a label."""
        self.redactions.append(admin_token)
        return self.run(
            "compose",
            "-p",
            state.project,
            "-f",
            str(state.compose_path),
            "--project-directory",
            str(state.directory),
            "--env-file",
            str(state.directory / "compose.env"),
            "exec",
            "-T",
            service,
            "python3",
            "/opt/relay/relay.py",
            "probe",
            timeout=180,
            what=f"probing {service}",
            stdin=admin_token.strip() + b"\n",
        )

    def up(self, state: StackState, service: str, timeout: int = 300) -> None:
        self.compose(
            state,
            "up",
            "--detach",
            "--wait",
            "--wait-timeout",
            str(timeout),
            "--no-deps",
            "--pull",
            "missing",
            service,
            timeout=timeout + 60,
            what=f"starting service {service}",
            binds=True,
        )

    def control(self, state: StackState, verb: str, service: str, timeout: int = 180) -> None:
        """`docker compose start|stop|restart SERVICE` on the existing compose file: no
        re-render, no recreate, no image pull. The stack's compose file declares no
        `depends_on`; `restart` still passes `--no-deps` so only this container restarts."""
        if verb not in ("start", "stop", "restart"):
            raise ValueError(f"unknown verb {verb!r}")
        arguments = ("restart", "--no-deps") if verb == "restart" else (verb,)
        self.compose(
            state,
            *arguments,
            service,
            timeout=timeout,
            what=f"docker compose {verb} {service}",
            binds=verb != "stop",
        )

    def containers(self, state: StackState) -> dict[str, dict]:
        """service -> {id, state, health, config} for this stack's containers."""
        if not state.compose_path.exists():
            return {}
        output = self.compose(state, "ps", "--all", "--format", "json", timeout=60)
        rows = []
        text = output.strip()
        if text.startswith("["):
            rows = json.loads(text)
        else:
            rows = [json.loads(line) for line in text.splitlines() if line.strip()]
        result = {}
        for row in rows:
            labels = _labels(row.get("Labels"))
            if labels.get(LABEL_STACK) != state.id:
                continue
            result[row.get("Service", "")] = {
                "id": row.get("ID", ""),
                "state": row.get("State", ""),
                "health": row.get("Health", ""),
                "config": labels.get("io.agentbreeder.config", ""),
            }
        return result

    def remove_container(self, container_id: str) -> None:
        """Remove one container by id: a relay whose `mcp:` entry is gone, which compose can't
        address once its service has left the compose file."""
        if not re.fullmatch(r"[0-9A-Za-z][0-9A-Za-z_.-]{0,127}", container_id):
            raise ValueError("invalid container id")
        self.run("rm", "--force", container_id, what="removing a dropped relay")

    def down(self, state: StackState) -> None:
        if state.compose_path.exists():
            self.compose(state, "down", "--remove-orphans", timeout=180, what="stopping the stack")

    def _logs_argv(
        self, state: StackState, service: str, tail: int, since: str | None, follow: bool
    ) -> list[str]:
        """`docker compose logs` of one service: no colour, no `name |` prefix (so Docker's
        16 KiB partial records can be joined like `logs ID`), timestamped. The service name
        was checked against stack.yaml by the engine; `since` against runtime.SINCE."""
        from agentbreeder.runtime import MAX_TAIL, SINCE

        if type(tail) is not int or not 1 <= tail <= MAX_TAIL:
            raise ServiceError("TAIL_INVALID", f"--tail must be 1..{MAX_TAIL}")
        if since is not None and not SINCE.fullmatch(since):
            raise ServiceError(
                "SINCE_INVALID", "--since must look like 10m, 2h or 2026-11-11T09:00:00Z"
            )
        arguments = [
            "compose", "-p", state.project, "-f", str(state.compose_path),
            "--project-directory", str(state.directory),
            "--env-file", str(state.directory / "compose.env"),
            "logs", "--no-color", "--no-log-prefix", "--timestamps", "--tail", str(tail),
        ]  # fmt: skip
        arguments += ["--since", since] if since else []
        arguments += ["--follow"] if follow else []
        return self._argv([*arguments, "--", service])

    def read_logs(
        self, state: StackState, service: str, tail: int, since: str | None = None
    ) -> tuple[str, bool]:
        """The service's recent output (as `Docker.logs`: 4 MiB cap keeping whole lines, long
        lines' partial records joined) and whether older output was dropped. Not redacted.
        Compose's own stderr is never read into a message (it can carry local details)."""
        from agentbreeder.runtime import LOG_LIMIT, _read_tail, join_partials

        argv = self._logs_argv(state, service, tail, since, follow=False)
        try:
            process = self._popen(
                argv,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                env=sanitised_environment(),
            )
        except OSError:
            raise ServiceError(
                "DOCKER_LOGS_FAILED", "docker compose logs failed to start"
            ) from None
        try:
            result = _read_tail(process, LOG_LIMIT, timeout=60)
        finally:
            if process.poll() is None:
                process.kill()
            process.wait()
        if result is None:
            raise ServiceError("DOCKER_LOGS_FAILED", "docker compose logs timed out")
        if process.returncode:
            raise ServiceError("DOCKER_LOGS_FAILED", "docker compose logs failed")
        data, truncated = result
        if truncated:
            data = data[data.find(b"\n") + 1 :] if b"\n" in data else b""
        data = b"\n".join(join_partials(line) for line in data.split(b"\n"))
        return data.decode("utf-8", "replace"), truncated

    def follow_logs(
        self, state: StackState, service: str, tail: int, since: str | None = None
    ) -> subprocess.Popen:
        """`docker compose logs --follow` of one service, as `runtime.start_follow`: in the
        caller's process group (a group kill reaches it), stdin closed, stderr discarded;
        stopped with `runtime.stop_follow`, which also stops compose's plugin process."""
        argv = self._logs_argv(state, service, tail, since, follow=True)
        try:
            return self._popen(
                argv,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.DEVNULL,
                env=sanitised_environment(),
            )
        except OSError:
            raise ServiceError(
                "DOCKER_LOGS_FAILED", "docker compose logs failed to start"
            ) from None

    # -- volumes and images -----------------------------------------------------------------------

    def volume_identity(self, name: str) -> str | None:
        try:
            created = self.run(
                "volume", "inspect", "--format", "{{.CreatedAt}}", name, what="volume inspect"
            )
        except ServiceError:
            return None
        return f"{name}@{created}"

    def stack_volumes(self, state: StackState) -> list[str]:
        output = self.run(
            "volume",
            "ls",
            "--quiet",
            "--filter",
            f"label={LABEL_STACK}={state.id}",
            what="listing volumes",
        )
        prefix = f"{state.project}-"
        return sorted(n for n in output.splitlines() if n.startswith(prefix))

    # -- usage (`services usage`) ---------------------------------------------------------------

    def labelled_containers(self, label: str, keys: tuple[str, ...]) -> list[list]:
        """Running containers matching one `label` filter (`key` or `key=value`), each as
        `[short id, value of keys[0], ...]` (a missing label is ""). The values come through
        Docker's own `json` template function, so no separator can be spoofed by a label."""
        fields = ["{{json .ID}}", *(f'{{{{json (.Label "{key}")}}}}' for key in keys)]
        output = self.run(
            "ps",
            "--filter",
            f"label={label}",
            "--format",
            "[" + ",".join(fields) + "]",
            timeout=30,
            what="listing containers",
        )
        rows = []
        for line in output.splitlines():
            try:
                row = json.loads(line)
            except (ValueError, RecursionError):
                continue
            if isinstance(row, list) and len(row) == len(keys) + 1:
                rows.append(row)
        return rows

    def disk_usage(self) -> dict:
        """`docker system df -v` as a document (Images, Containers, Volumes, BuildCache)."""
        output = self.run(
            "system", "df", "-v", "--format", "{{json .}}", timeout=120, what="docker system df"
        )
        try:
            document = json.loads(output)
        except (ValueError, RecursionError):
            raise ServiceError("DOCKER_FAILED", "docker system df returned no JSON") from None
        if not isinstance(document, dict):
            raise ServiceError("DOCKER_FAILED", "docker system df returned no JSON")
        return document

    def remove_volume(self, name: str) -> None:
        self.run("volume", "rm", name, what="removing a volume")

    def stack_images(self, state: StackState) -> list[str]:
        """Service images built for this stack (`agentbreeder-svc/<stack-id>-<service>:<hash>`)."""
        prefix = f"agentbreeder-svc/{state.id}-"
        output = self.run(
            "image",
            "ls",
            "--format",
            "{{.Repository}}:{{.Tag}}",
            "--filter",
            f"reference={prefix}*",
            what="listing images",
        )
        return sorted(n for n in output.splitlines() if n.startswith(prefix))

    def remove_image(self, tag: str) -> None:
        self.run("image", "rm", tag, what="removing an image")

    def build(self, context: Path, tag: str) -> None:
        self.run(
            "build",
            "--pull=false",
            "--tag",
            tag,
            "--label",
            "io.agentbreeder.built=service",
            str(context),
            timeout=1800,
            what="building a service image",
        )

    def image_exists(self, tag: str) -> bool:
        try:
            self.run("image", "inspect", "--format", "{{.Id}}", tag, what="image inspect")
        except ServiceError:
            return False
        return True

    # -- one-shot containers ----------------------------------------------------------------------

    def _oneshot_argv(self, state, *, label, name, network, user, mounts, env, image, command):
        argv = [
            "run",
            "--rm",
            "--name",
            name,
            "--log-driver",
            "none",
            "--pull",
            "never",
            "--network",
            network,
            "--read-only",
            "--cap-drop",
            "ALL",
            "--security-opt",
            "no-new-privileges",
            "--tmpfs",
            TMPFS,
            "--pids-limit",
            "128",
            "--label",
            f"{LABEL_STACK}={state.id}",
            "--label",
            f"io.agentbreeder.step={label}",
        ]
        if user:
            argv += ["--user", user]
        for source, target in mounts:
            argv += ["--mount", f"type=bind,src={source},dst={target},readonly"]
        for key, value in sorted(env.items()):
            argv.append(f"--env={key}={value}")
        # The command is the whole argv; the image ENTRYPOINT never wraps it.
        return [*argv, "--entrypoint", command[0], image, *command[1:]]

    def oneshot(
        self,
        state: StackState,
        *,
        label: str,
        network: str,
        image: str,
        command: list[str],
        user: str | None = None,
        mounts: list[tuple[Path, str]] = (),
        env: dict[str, str] | None = None,
        capture: bool = False,
        timeout: float = 300,
    ) -> bytes:
        """Run a step to completion. With `capture`, return stdout (1..8 KiB, else fail).
        The deadline covers the whole run, and a step that times out or writes too much is
        removed by name (killing the docker client alone would leave the container running)."""
        name = f"{state.project}-step-{secrets.token_hex(6)}"
        argv = self._argv(
            self._oneshot_argv(
                state,
                label=label,
                name=name,
                network=network,
                user=user,
                mounts=mounts,
                env=env or {},
                image=image,
                command=command,
            )
        )
        try:
            process = self._popen(
                argv,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE if capture else subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                env=sanitised_environment(),
            )
        except OSError:
            raise ServiceError("ONESHOT_FAILED", f"{label} could not start") from None
        chunks: list[bytes] = []
        overflow = threading.Event()

        def read() -> None:
            data = process.stdout.read(ONESHOT_LIMIT + 1)
            chunks.append(data)
            if len(data) > ONESHOT_LIMIT:
                overflow.set()

        reader = threading.Thread(target=read, daemon=True) if capture else None
        if reader is not None:
            reader.start()
        deadline = self._clock() + timeout
        code = None
        try:
            while code is None:
                if overflow.is_set():
                    self._abort(process, name)
                    raise ServiceError("ONESHOT_OUTPUT", f"{label} wrote more than 8 KiB")
                if self._clock() >= deadline:
                    self._abort(process, name)
                    raise ServiceError("ONESHOT_FAILED", f"{label} timed out")
                try:
                    code = process.wait(timeout=0.2)
                except subprocess.TimeoutExpired:
                    continue
            if reader is not None:
                reader.join(timeout=5)
        finally:
            if capture and process.stdout:
                process.stdout.close()
        output = chunks[0] if chunks else b""
        if len(output) > ONESHOT_LIMIT:
            raise ServiceError("ONESHOT_OUTPUT", f"{label} wrote more than 8 KiB")
        if code:
            raise ServiceError("ONESHOT_FAILED", f"{label} exited with status {code}")
        if capture:
            output = output.strip()
            if not output:
                raise ServiceError("ONESHOT_OUTPUT", f"{label} wrote nothing")
        return output

    def _abort(self, process, name: str) -> None:
        process.kill()
        try:
            process.wait(timeout=30)
        except subprocess.TimeoutExpired:
            pass
        try:
            self.run("rm", "--force", name, timeout=60, what="removing a stopped step")
        except ServiceError:
            pass

    def probe(
        self,
        state: StackState,
        network: str,
        url: str,
        timeout: float = 180,
        sleep: Callable = time.sleep,
        clock: Callable = time.monotonic,
    ) -> bool:
        """HTTP health from inside the stack network, with a pinned probe image."""
        deadline = clock() + timeout
        while True:
            try:
                self.oneshot(
                    state,
                    label="health-probe",
                    network=network,
                    image=PROBE_IMAGE,
                    command=["python3", "-c", PROBE, url],
                    user="65532:65532",
                    timeout=30,
                )
                return True
            except ServiceError:
                if clock() >= deadline:
                    return False
                sleep(2)

    def pull(self, image: str) -> None:
        if not self.image_exists(image):
            self.run("image", "pull", image, timeout=600, what="pulling an image")


def _labels(value) -> dict[str, str]:
    if isinstance(value, dict):
        return value
    result = {}
    for part in (value or "").split(","):
        key, _, item = part.partition("=")
        if key:
            result[key] = item
    return result


def _text(value) -> str:
    if isinstance(value, bytes):
        return value.decode("utf-8", "replace")
    return value or ""
